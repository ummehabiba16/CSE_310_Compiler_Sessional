func:
	PUSH EBP
	MOV EBP, ESP
	SUB ESP, 4
	MOV EAX, 0
	PUSH EAX
	MOV EAX,[EBP+8]
	PUSH EAX
	POP EAX
	POP EBX
	CMP EAX, EBX
	JE L0
	MOV EAX, 0
	JMP L1
L0:
	MOV EAX, 1
L1:
	PUSH EAX
	POP EAX
	TEST EAX, EAX
	JE L2
	MOV EAX, 0
	PUSH EAX
	POP EAX
	JMP func_exit
L2:
	MOV EAX,[EBP+8]
	PUSH EAX
	POP EAX
	MOV [EBP-4], EAX
	PUSH EAX
	POP EAX
	MOV EAX,[EBP-4]
	PUSH EAX
	MOV EAX, 1
	PUSH EAX
	MOV EAX,[EBP+8]
	PUSH EAX
	POP EAX
	POP EBX
	SUB EAX, EBX
	PUSH EAX
	CALL func
	PUSH EAX
	POP EAX
	POP EBX
	ADD EAX, EBX
	PUSH EAX
	POP EAX
	JMP func_exit
func_exit:

	ADD ESP, 4
	POP EBP
	RET 4
