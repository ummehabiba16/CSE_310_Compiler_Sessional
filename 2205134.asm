format ELF executable 3
entry main
segment readable writeable
segment readable executable
main:
	PUSH EBP
	MOV EBP, ESP
	SUB ESP, 4
	SUB ESP, 4
	MOV EAX, 5
	PUSH EAX
	MOV [EBP-4], EAX
	POP EAX
	MOV EAX, [EBP-4]
	PUSH EAX
	DEC EAX
	MOV [EBP-4], EAX
	POP EAX

	PUSH EAX
	MOV [EBP-8], EAX
	POP EAX
	; print b
	MOV EAX, [EBP-8]
	PUSH EAX
	CALL OUTDEC
	POP EAX
	; print a
	MOV EAX, [EBP-4]
	PUSH EAX
	CALL OUTDEC
	POP EAX
	MOV EAX, 2
	PUSH EAX
	MOV [EBP-4], EAX
	POP EAX
	MOV EAX, [EBP-4]
	PUSH EAX
	INC EAX
	MOV [EBP-4], EAX
	POP EAX

	PUSH EAX
	MOV [EBP-8], EAX
	POP EAX
	; print b
	MOV EAX, [EBP-8]
	PUSH EAX
	CALL OUTDEC
	POP EAX
	; print a
	MOV EAX, [EBP-4]
	PUSH EAX
	CALL OUTDEC
	POP EAX
main_exit:

	ADD ESP, 8
	POP EBP
	MOV EAX, 1    ; syscall number: sys_exit
	XOR EBX, EBX  ; exit code 0 (success)
	INT 0x80
	POP EBP
	RET


; ---- OUTDEC: print integer in EAX as decimal, followed by newline ----
OUTDEC:
	PUSH EBX
	PUSH ECX
	PUSH EDX
	PUSH ESI
	OR   EAX, EAX
	JGE  OUTDEC_POSITIVE
	NEG  EAX
	PUSH EAX
	SUB  ESP, 4
	MOV  byte [ESP], '-'
	MOV  EAX, 4
	MOV  EBX, 1
	MOV  ECX, ESP
	MOV  EDX, 1
	INT  0x80
	ADD  ESP, 4
	POP  EAX
OUTDEC_POSITIVE:
	XOR  ECX, ECX
	MOV  EBX, 10
OUTDEC_DIGIT_LOOP:
	XOR  EDX, EDX
	DIV  EBX
	ADD  DL, 30h
	PUSH EDX
	INC  ECX
	TEST EAX, EAX
	JNZ  OUTDEC_DIGIT_LOOP
	MOV  ESI, ECX
	MOV  EBX, 1
	MOV  EDX, 1
OUTDEC_PRINT_LOOP:
	TEST ESI, ESI
	JZ   OUTDEC_NEWLINE
	MOV  EAX, 4
	MOV  ECX, ESP
	INT  0x80
	ADD  ESP, 4
	DEC  ESI
	JMP  OUTDEC_PRINT_LOOP
OUTDEC_NEWLINE:
	SUB  ESP, 4
	MOV  byte [ESP], 10
	MOV  EAX, 4
	MOV  ECX, ESP
	INT  0x80
	ADD  ESP, 4
	POP  ESI
	POP  EDX
	POP  ECX
	POP  EBX
	RET