format ELF executable 3
entry main
segment readable writeable
segment readable executable
main:
	PUSH EBP
	MOV EBP, ESP
	SUB ESP, 4
	SUB ESP, 4
	SUB ESP, 4
	SUB ESP, 4
	MOV EAX, 0
	PUSH EAX
	MOV [EBP-4], EAX
	POP EAX
L0:
	MOV EAX, 6
	PUSH EAX
	MOV EAX, [EBP-4]
	PUSH EAX
	POP EAX
	POP EBX
	CMP EAX, EBX
	JL L1
	MOV EAX, 0
	JMP L2
L1:
	MOV EAX, 1
L2:
	PUSH EAX
	TEST EAX, EAX
	JE L3
	; print i
	MOV EAX, [EBP-4]
	PUSH EAX
	CALL OUTDEC
	POP EAX
	MOV EAX, [EBP-4]

	PUSH EAX
	INC EAX
	MOV [EBP-4], EAX
	POP EAX
	PUSH EAX
	JMP L0
	L3:
	MOV EAX, 4
	PUSH EAX
	MOV [EBP-12], EAX
	POP EAX
	MOV EAX, 6
	PUSH EAX
	MOV [EBP-16], EAX
	POP EAX
L4:
	MOV EAX, 0
	PUSH EAX
	MOV EAX, [EBP-12]
	PUSH EAX
	POP EAX
	POP EBX
	CMP EAX, EBX
	JG L5
	MOV EAX, 0
	JMP L6
L5:
	MOV EAX, 1
L6:
	PUSH EAX
	Test EAX, EAX
	JE L7
	MOV EAX, 3
	PUSH EAX
	MOV EAX, [EBP-16]
	PUSH EAX
	POP EAX
	POP EBX
	ADD EAX, EBX
	PUSH EAX
	MOV [EBP-16], EAX
	POP EAX
	MOV EAX, [EBP-12]

	PUSH EAX
	DEC EAX
	MOV [EBP-12], EAX
	POP EAX
	PUSH EAX
	JMP L4
L7:
	; print ll
	MOV EAX, [EBP-16]
	PUSH EAX
	CALL OUTDEC
	POP EAX
	; print k
	MOV EAX, [EBP-12]
	PUSH EAX
	CALL OUTDEC
	POP EAX
	MOV EAX, 4
	PUSH EAX
	MOV [EBP-12], EAX
	POP EAX
	MOV EAX, 6
	PUSH EAX
	MOV [EBP-16], EAX
	POP EAX
L8:
	MOV EAX, [EBP-12]

	PUSH EAX
	DEC EAX
	MOV [EBP-12], EAX
	POP EAX
	PUSH EAX
	Test EAX, EAX
	JE L9
	MOV EAX, 3
	PUSH EAX
	MOV EAX, [EBP-16]
	PUSH EAX
	POP EAX
	POP EBX
	ADD EAX, EBX
	PUSH EAX
	MOV [EBP-16], EAX
	POP EAX
	JMP L8
L9:
	; print ll
	MOV EAX, [EBP-16]
	PUSH EAX
	CALL OUTDEC
	POP EAX
	; print k
	MOV EAX, [EBP-12]
	PUSH EAX
	CALL OUTDEC
	POP EAX
	MOV EAX, 0
	PUSH EAX
	POP EAX
	JMP main_exit
main_exit:

	ADD ESP, 16
	POP EBP
	MOV EAX, 1    ; syscall number: sys_exit
	XOR EBX, EBX  ; exit code 0 (success)
	INT 0x80
	POP EBP
	RET


; ---- OUTDEC: print integer in EAX as decimal, followed by newline ----
OUTDEC:
	PUSH EBX
	PUSH ECX
	PUSH EDX
	PUSH ESI
	OR   EAX, EAX
	JGE  OUTDEC_POSITIVE
	NEG  EAX
	PUSH EAX
	SUB  ESP, 4
	MOV  byte [ESP], '-'
	MOV  EAX, 4
	MOV  EBX, 1
	MOV  ECX, ESP
	MOV  EDX, 1
	INT  0x80
	ADD  ESP, 4
	POP  EAX
OUTDEC_POSITIVE:
	XOR  ECX, ECX
	MOV  EBX, 10
OUTDEC_DIGIT_LOOP:
	XOR  EDX, EDX
	DIV  EBX
	ADD  DL, 30h
	PUSH EDX
	INC  ECX
	TEST EAX, EAX
	JNZ  OUTDEC_DIGIT_LOOP
	MOV  ESI, ECX
	MOV  EBX, 1
	MOV  EDX, 1
OUTDEC_PRINT_LOOP:
	TEST ESI, ESI
	JZ   OUTDEC_NEWLINE
	MOV  EAX, 4
	MOV  ECX, ESP
	INT  0x80
	ADD  ESP, 4
	DEC  ESI
	JMP  OUTDEC_PRINT_LOOP
OUTDEC_NEWLINE:
	SUB  ESP, 4
	MOV  byte [ESP], 10
	MOV  EAX, 4
	MOV  ECX, ESP
	INT  0x80
	ADD  ESP, 4
	POP  ESI
	POP  EDX
	POP  ECX
	POP  EBX
	RET