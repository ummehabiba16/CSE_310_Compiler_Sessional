format ELF executable 3
entry main
segment readable writeable
	i dd 1 dup(0)
	j dd 1 dup(0)
segment readable executable
main:
	PUSH EBP
	MOV EBP, ESP
	SUB ESP, 4
	SUB ESP, 4
	SUB ESP, 4
	SUB ESP, 4
	SUB ESP, 4
	SUB ESP, 4
	MOV EAX, 1
	MOV [i], EAX
	; print i
	MOV EAX, [i]
	PUSH EAX
	CALL OUTDEC
	POP EAX
	MOV EAX, 8
	PUSH EAX
	MOV EAX, 5
	POP EBX
	ADD EAX, EBX
	MOV [j], EAX
	; print j
	MOV EAX, [j]
	PUSH EAX
	CALL OUTDEC
	POP EAX
	MOV EAX,[j]
	PUSH EAX
	MOV EAX, 2
	POP EBX
	MUL EBX
	PUSH EAX
	MOV EAX,[i]
	POP EBX
	ADD EAX, EBX
	MOV [EBP-4], EAX
	; print k
	MOV EAX, [EBP-4]
	PUSH EAX
	CALL OUTDEC
	POP EAX
	MOV EAX, 9
	PUSH EAX
	MOV EAX,[EBP-4]
	POP EBX
	XOR EDX, EDX
	DIV EBX
	MOV EAX, EDX
	MOV [EBP-12], EAX
	; print m
	MOV EAX, [EBP-12]
	PUSH EAX
	CALL OUTDEC
	POP EAX
	MOV EAX,[EBP-8]
	PUSH EAX
	MOV EAX,[EBP-12]
	POP EBX
	CMP EAX, EBX
	JLE L0
	MOV EAX, 0
	JMP L1
L0:
	MOV EAX, 1
L1:
	MOV [EBP-16], EAX
	; print n
	MOV EAX, [EBP-16]
	PUSH EAX
	CALL OUTDEC
	POP EAX
	MOV EAX,[j]
	PUSH EAX
	MOV EAX,[i]
	POP EBX
	CMP EAX, EBX
	JNE L2
	MOV EAX, 0
	JMP L3
L2:
	MOV EAX, 1
L3:
	MOV [EBP-20], EAX
	; print o
	MOV EAX, [EBP-20]
	PUSH EAX
	CALL OUTDEC
	POP EAX
	MOV EAX,[EBP-16]
	TEST EAX, EAX
	JNE L4
	MOV EAX,[EBP-20]
	TEST EAX, EAX
	JNE L4
	MOV EAX, 0
	JMP L5
L4:
	MOV EAX, 1
L5:
	MOV [EBP-24], EAX
	; print p
	MOV EAX, [EBP-24]
	PUSH EAX
	CALL OUTDEC
	POP EAX
	MOV EAX,[EBP-16]
	TEST EAX, EAX
	JE L6
	MOV EAX,[EBP-20]
	TEST EAX, EAX
	JE L6
	MOV EAX, 1
	JMP L7
L6:
	MOV EAX, 0
L7:
	MOV [EBP-24], EAX
	; print p
	MOV EAX, [EBP-24]
	PUSH EAX
	CALL OUTDEC
	POP EAX
	MOV EAX, [EBP-24]

	PUSH EAX
	INC EAX
	MOV [EBP-24], EAX
	POP EAX
	; print p
	MOV EAX, [EBP-24]
	PUSH EAX
	CALL OUTDEC
	POP EAX
	MOV EAX,[EBP-24]
	PUSH EAX
	NEG EAX
	MOV [EBP-4], EAX
	; print k
	MOV EAX, [EBP-4]
	PUSH EAX
	CALL OUTDEC
	POP EAX
	MOV EAX, 0
	JMP main_exit
main_exit:

	MOV EAX, 1    ; syscall number: sys_exit
	XOR EBX, EBX  ; exit code 0 (success)
	INT 0x80



; ---- OUTDEC: print integer in EAX as decimal, followed by newline ----
OUTDEC:
	PUSH EBX
	PUSH ECX
	PUSH EDX
	PUSH ESI
	OR   EAX, EAX
	JGE  OUTDEC_POSITIVE
	NEG  EAX
	PUSH EAX
	SUB  ESP, 4
	MOV  byte [ESP], '-'
	MOV  EAX, 4
	MOV  EBX, 1
	MOV  ECX, ESP
	MOV  EDX, 1
	INT  0x80
	ADD  ESP, 4
	POP  EAX
OUTDEC_POSITIVE:
	XOR  ECX, ECX
	MOV  EBX, 10
OUTDEC_DIGIT_LOOP:
	XOR  EDX, EDX
	DIV  EBX
	ADD  DL, 30h
	PUSH EDX
	INC  ECX
	TEST EAX, EAX
	JNZ  OUTDEC_DIGIT_LOOP
	MOV  ESI, ECX
	MOV  EBX, 1
	MOV  EDX, 1
OUTDEC_PRINT_LOOP:
	TEST ESI, ESI
	JZ   OUTDEC_NEWLINE
	MOV  EAX, 4
	MOV  ECX, ESP
	INT  0x80
	ADD  ESP, 4
	DEC  ESI
	JMP  OUTDEC_PRINT_LOOP
OUTDEC_NEWLINE:
	SUB  ESP, 4
	MOV  byte [ESP], 10
	MOV  EAX, 4
	MOV  ECX, ESP
	INT  0x80
	ADD  ESP, 4
	POP  ESI
	POP  EDX
	POP  ECX
	POP  EBX
	RET
