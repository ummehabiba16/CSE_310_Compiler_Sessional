; ---- OUTDEC: print integer in EAX as decimal, followed by newline ----
OUTDEC:
	PUSH EBX
	PUSH ECX
	PUSH EDX
	PUSH ESI
	OR   EAX, EAX
	JGE  OUTDEC_POSITIVE
	NEG  EAX
	PUSH EAX
	SUB  ESP, 4
	MOV  byte [ESP], '-'
	MOV  EAX, 4
	MOV  EBX, 1
	MOV  ECX, ESP
	MOV  EDX, 1
	INT  0x80
	ADD  ESP, 4
	POP  EAX
OUTDEC_POSITIVE:
	XOR  ECX, ECX
	MOV  EBX, 10
OUTDEC_DIGIT_LOOP:
	XOR  EDX, EDX
	DIV  EBX
	ADD  DL, 30h
	PUSH EDX
	INC  ECX
	TEST EAX, EAX
	JNZ  OUTDEC_DIGIT_LOOP
	MOV  ESI, ECX
	MOV  EBX, 1
	MOV  EDX, 1
OUTDEC_PRINT_LOOP:
	TEST ESI, ESI
	JZ   OUTDEC_NEWLINE
	MOV  EAX, 4
	MOV  ECX, ESP
	INT  0x80
	ADD  ESP, 4
	DEC  ESI
	JMP  OUTDEC_PRINT_LOOP
OUTDEC_NEWLINE:
	SUB  ESP, 4
	MOV  byte [ESP], 10
	MOV  EAX, 4
	MOV  ECX, ESP
	INT  0x80
	ADD  ESP, 4
	POP  ESI
	POP  EDX
	POP  ECX
	POP  EBX
	RET
